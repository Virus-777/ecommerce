#!/usr/bin/env node
/**
 * Verify the coverage audit (docs/api/audit/*.json) against the API design.
 *   node docs/api/tools/audit.mjs
 *
 * Audit entries (screens-*.json):
 *   { screen, state?, element, kind: "action"|"data", status: "covered"|"missing"|"client-only"|"later"|"not-in-plan",
 *     api: ["POST /api/store/cart/lines", "gql store/ProductPage", "gql store:Product.reviewSummary"], note?, proposal? }
 * Plan entries (plan.json):
 *   { chapter, requirement, status: "covered"|"missing"|"non-api", api: [...], note? }
 *
 * Checks that every "covered" reference exists: REST "METHOD /full/path" (path params as {x}),
 * GraphQL screen query "gql <area>/<Name>", or GraphQL field "gql <area>:<Type>.<field>".
 * Prints totals and every entry still marked "missing".
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const apiDir = join(dirname(fileURLToPath(import.meta.url)), '..');
const common = JSON.parse(readFileSync(join(apiDir, 'spec', 'common.json'), 'utf8'));
const routes = new Set();
for (const f of readdirSync(join(apiDir, 'spec', 'modules')).filter((x) => x.endsWith('.json'))) {
  const m = JSON.parse(readFileSync(join(apiDir, 'spec', 'modules', f), 'utf8'));
  for (const e of m.endpoints) routes.add(`${e.method} ${(common.areas[e.area].prefix.replace('{module}', m.name) + e.path).replace(/\{\w+\}/g, '{}')}`);
}
const ops = new Set();
for (const area of ['store', 'seller', 'admin']) {
  const dir = join(apiDir, 'graphql', 'operations', area);
  if (existsSync(dir)) for (const f of readdirSync(dir).filter((x) => x.endsWith('.graphql'))) ops.add(`${area}/${f.replace('.graphql', '')}`);
}
const gqlFields = new Set();
for (const area of ['store', 'seller', 'admin']) {
  const p = join(apiDir, 'graphql', `schema.${area}.graphql`);
  if (!existsSync(p)) continue;
  let current = null;
  for (const line of readFileSync(p, 'utf8').split('\n')) {
    const t = line.match(/^(?:extend\s+)?(?:type|input|interface)\s+(\w+)/);
    if (t) { current = t[1]; continue; }
    if (/^\}/.test(line)) { current = null; continue; }
    const f = current && line.match(/^\s+(\w+)\s*[(:]/);
    if (f) gqlFields.add(`${area}:${current}.${f[1]}`);
  }
}

const exists = (ref) => {
  const r = ref.trim();
  if (r.startsWith('gql ')) {
    const x = r.slice(4).trim();
    return x.includes(':') ? gqlFields.has(x) : ops.has(x);
  }
  const m = r.match(/^(GET|POST|PUT|PATCH|DELETE)\s+(\S+)/);
  return Boolean(m && routes.has(`${m[1]} ${m[2].replace(/\{\w+\}/g, '{}')}`));
};

const dir = join(apiDir, 'audit');
if (!existsSync(dir)) { console.log('No audit files yet.'); process.exit(0); }
let bad = 0;
const totals = {};
const missing = [];
for (const f of readdirSync(dir).filter((x) => x.endsWith('.json')).sort()) {
  const entries = JSON.parse(readFileSync(join(dir, f), 'utf8'));
  const t = (totals[f] = { entries: entries.length });
  for (const e of entries) {
    t[e.status] = (t[e.status] ?? 0) + 1;
    if (e.status === 'missing') missing.push(`${f}: ${e.screen ?? `ch.${e.chapter}`} · ${e.element ?? e.requirement}`);
    if (e.status === 'covered') {
      if (!e.api?.length) { bad++; console.log(`NO REF   ${f}: ${e.screen ?? `ch.${e.chapter}`} · ${e.element ?? e.requirement}`); }
      for (const ref of e.api ?? []) if (!exists(ref)) { bad++; console.log(`BAD REF  ${f}: ${e.screen ?? `ch.${e.chapter}`} · ${e.element ?? e.requirement} → ${ref}`); }
    }
  }
}
console.table(totals);
// Viewer data: every audit file, as-is, for the Coverage page
const all = Object.fromEntries(readdirSync(dir).filter((x) => x.endsWith('.json')).sort().map((f) => [f.replace('.json', ''), JSON.parse(readFileSync(join(dir, f), 'utf8'))]));
writeFileSync(join(apiDir, 'viewer', 'audit-data.js'), `/* Generated by docs/api/tools/audit.mjs. Do not edit. */\nwindow.API_AUDIT = ${JSON.stringify({ files: all, generatedAt: new Date().toISOString().slice(0, 10) })};\n`);
if (missing.length) console.log(`\nStill missing (${missing.length}):\n${missing.map((m) => `  - ${m}`).join('\n')}`);
console.log(bad ? `\n${bad} broken reference(s).` : '\nAll cited endpoints and queries exist.');
process.exit(bad || missing.length ? 1 : 0);
