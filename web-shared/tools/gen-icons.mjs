// Generates src/ui/icons.generated.ts: a tree-shakable map from the design's Lucide icon
// names (kebab-case, as in the design export's data-lucide attributes) to lucide-react components.
// Sources: tools/icons.design.txt (names used by the design) + tools/icons.extra.txt (names added later).
// Run: npm run gen:icons
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import * as lucide from 'lucide-react';

const read = (f) => (existsSync(f) ? readFileSync(f, 'utf8').split(/\r?\n/).map((s) => s.trim()).filter((s) => s && !s.startsWith('#')) : []);
const names = [...new Set([...read('tools/icons.design.txt'), ...read('tools/icons.extra.txt')])].sort();
const pascal = (n) => n.replace(/(^|-)([a-z0-9])/g, (_, __, c) => c.toUpperCase());
const missing = [];
const rows = [];
for (const n of names) {
  const p = pascal(n);
  const exp = lucide[p] ? p : lucide[p + 'Icon'] ? p + 'Icon' : null;
  if (!exp) { missing.push(n); continue; }
  rows.push([n, exp]);
}
if (missing.length) { console.error('Unknown Lucide icons:', missing.join(', ')); process.exit(1); }
const out = `// Generated by tools/gen-icons.mjs. Do not edit; add names to tools/icons.extra.txt and run \`npm run gen:icons\`.
import {
${rows.map(([, e]) => `  ${e},`).join('\n')}
} from 'lucide-react';
import type { LucideIcon } from 'lucide-react';

export const ICONS = {
${rows.map(([n, e]) => `  '${n}': ${e},`).join('\n')}
} satisfies Record<string, LucideIcon>;

export type IconName = keyof typeof ICONS;
`;
writeFileSync('src/ui/icons.generated.ts', out);
console.log(`icons.generated.ts: ${rows.length} icons`);
