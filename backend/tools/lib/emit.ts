/**
 * Emits src/spec/<module>.ts (generated, never edited by hand) from one module spec.
 */
import { mergeConsumes } from './scaffold.js';
import { planTables, tsOfColumn } from './sql.js';
import { camel, pascal, type CommonSpec, type ModuleSpec } from './spec.js';
import { translateSignature, TypeContext, type Parsed } from './types.js';

export const GENERATED = (source: string) =>
  `// GENERATED by \`npm run gen\` from ${source}. Do not edit: change the spec and regenerate.\n`;

const str = (s: string) => JSON.stringify(s);
const doc = (text: string | undefined, indent = '') =>
  text ? `${indent}/** ${text.replace(/\*\//g, '*\\/').replace(/\n/g, ` \n${indent} * `)} */\n` : '';

export function eventTypeName(event: string) {
  return `${event.split('.').map((p) => pascal(p.replace(/_/g, '-'))).join('')}Event`;
}

export function emitCommon(common: CommonSpec): { code: string; problems: string[] } {
  const ctx = new TypeContext(null, new Set(Object.keys(common.types)), new Map());
  const parts: string[] = [GENERATED('docs/api/spec/common.json')];
  parts.push(`import { z } from 'zod';

/** Every named API type is registered here; /docs renders them as OpenAPI components. */
export const apiTypes = z.registry<{ id: string }>();

/** Query arrays accept repeated keys (?a=1&a=2) and comma-separated values (?a=1,2). */
export const queryArray = <T extends z.ZodType>(item: T) =>
  z.preprocess((v) => (v === undefined || Array.isArray(v) ? v : String(v).split(',').filter(Boolean)), z.array(item));

/** Paged response, the same for every list: cursor for the Android app, page numbers for the website. */
export interface Page<T> {
  items: T[];
  /** Pass as ?cursor= for the next batch (app). Null at the end. */
  nextCursor: string | null;
  page?: number;
  totalPages?: number;
  total?: number;
}
export const page = <T extends z.ZodType>(item: T) =>
  z.object({
    items: z.array(item),
    nextCursor: z.string().nullable().describe('Pass as ?cursor= for the next batch (app). Null at the end.'),
    page: z.number().int().optional(),
    totalPages: z.number().int().optional(),
    total: z.number().int().optional(),
  });

/** Paging input (query string of every \`paging: true\` endpoint). */
export interface PageInput {
  cursor?: string;
  page?: number;
  limit?: number;
}
export const pageQuery = {
  cursor: z.string().optional().describe(${str(String((common.pagination.query.cursor as { desc?: string }).desc ?? ''))}),
  page: z.coerce.number().int().min(1).optional().describe(${str(String((common.pagination.query.page as { desc?: string }).desc ?? ''))}),
  limit: z.coerce.number().int().min(1).max(100).optional().describe(${str(String((common.pagination.query.limit as { desc?: string }).desc ?? ''))}),
};
export const DEFAULT_PAGE_LIMIT = 24;
export const MAX_PAGE_LIMIT = 100;
`);
  for (const [name, t] of Object.entries(common.types)) {
    const p = ctx.objectParsed(t, `common.${name}`);
    const fields = fieldsOfParsed(p);
    parts.push(`export interface ${name} ${ctx.tsObject(fields, '', 'data')}\n`);
    parts.push(`export const ${name}: z.ZodType<${name}> = ${ctx.zodObject(fields, 'data', '')}.register(apiTypes, { id: ${str(name)} });\n`);
  }
  parts.push(`/** Error codes shared by every module (common.json "errors"). */
export const commonErrors = ${JSON.stringify(common.errors, null, 2)} as const;

export type CommonErrorCode = keyof typeof commonErrors;

export const info = ${JSON.stringify(common.info, null, 2)} as const;

export const servers = ${JSON.stringify((common as unknown as { servers: unknown }).servers ?? [], null, 2)};

export const areas = ${JSON.stringify(common.areas, null, 2)} as const;

export const headers = ${JSON.stringify(common.headers, null, 2)} as const;
`);
  return { code: parts.join('\n'), problems: ctx.problems };
}

export function emitModule(mod: ModuleSpec, common: CommonSpec, byName: Map<string, ModuleSpec>): { code: string; problems: string[]; warnings: string[] } {
  const ctx = new TypeContext(mod, new Set(Object.keys(common.types)), byName);
  const body: string[] = [];
  const P = pascal(mod.name);

  /* ---------------- types */
  body.push('/* ------------------------------------------------------------------ types */\n');
  for (const [name, t] of Object.entries(mod.types ?? {})) {
    const p = ctx.objectParsed(t, `${mod.name}.types.${name}`);
    const fields = fieldsOfParsed(p);
    body.push(`export interface ${name} ${ctx.tsObject(fields, '', 'data')}\n`);
    body.push(`export const ${name}: z.ZodType<${name}> = ${ctx.zodObject(fields, 'data', '')}.register(common.apiTypes, { id: ${str(`${mod.name}.${name}`)} });\n`);
  }
  ctx.imports.add('common');

  /* ---------------- events */
  body.push('/* ------------------------------------------------------------------ events */\n');
  const publishes = mod.events?.publishes ?? [];
  for (const e of publishes) {
    const n = eventTypeName(e.name);
    const p = ctx.objectParsed(e.payload ?? {}, `${mod.name} event ${e.name}`);
    const fields = fieldsOfParsed(p);
    body.push(`${doc(`${e.name}: ${e.when}`)}export interface ${n} ${ctx.tsObject(fields, '', 'data')}\n`);
    body.push(`export const ${n}: z.ZodType<${n}> = ${ctx.zodObject(fields, 'data', '')};\n`);
  }

  /* ---------------- public API */
  body.push('/* ------------------------------------------------------------------ public API (in-process) */\n');
  body.push(`/** What other modules may call in-process: \`ctx.use('${mod.name}')\` (or \`ctx.tryUse\` for an optional dependency). */`);
  body.push(`export interface ${P}PublicApi {`);
  for (const f of mod.publicApi ?? []) {
    const s = translateSignature(f.signature, ctx, `${mod.name}.publicApi.${f.name}`);
    body.push(`${doc(`${f.desc}${f.usedBy?.length ? ` Used by: ${f.usedBy.join(', ')}.` : ''}`, '  ')}  ${f.name}${s.generics}(${s.params}): Promise<${s.returns}>;`);
  }
  body.push('}\n');

  /* ---------------- tables */
  const tableProblems: string[] = [];
  const plans = planTables(mod, tableProblems);
  ctx.problems.push(...tableProblems);
  body.push('/* ------------------------------------------------------------------ tables (Kysely row types) */\n');
  body.push(`/** Tables in the \`${mod.name.replace(/-/g, '_')}\` schema. Use with \`ctx.db\` (already scoped to the schema). */`);
  body.push(`export interface ${P}Db {`);
  for (const { table, columns } of plans) {
    body.push(`${doc(table.desc, '  ')}  ${table.name}: {`);
    for (const c of columns) body.push(`${doc(c.comment ?? undefined, '    ')}    ${c.name}: ${tsOfColumn(c)};`);
    body.push('  };');
  }
  body.push('}\n');

  /* ---------------- endpoints */
  body.push('/* ------------------------------------------------------------------ endpoints */\n');
  body.push(`export const endpoints = defineEndpoints(${str(mod.name)}, {`);
  for (const ep of mod.endpoints) {
    const where = `${mod.name}.${ep.id}`;
    const lines: string[] = [];
    lines.push(`area: ${str(ep.area)}`, `method: ${str(ep.method)}`, `path: ${str(ep.path)}`, `auth: ${str(ep.auth)}`);
    if (ep.permission) lines.push(`permission: ${str(ep.permission)}`);
    lines.push(`summary: ${str(ep.summary)}`);
    if (ep.desc) lines.push(`desc: ${str(ep.desc)}`);
    if (ep.params) lines.push(`params: () =>\n      ${ctx.zodObject(fieldsOf(ctx, ep.params, `${where} params`), 'query', '      ')}`);
    if (ep.query) lines.push(`query: () =>\n      ${ctx.zodObject(fieldsOf(ctx, ep.query, `${where} query`), 'query', '      ')}`);
    if (ep.paging) lines.push('paging: true');
    if (ep.body !== undefined) lines.push(`body: () => ${schemaOf(ctx, ep.body, `${where} body`)}`);
    lines.push(ep.response === null || ep.response === undefined ? 'response: null' : `response: () => ${schemaOf(ctx, ep.response, `${where} response`)}`);
    lines.push(`status: ${ep.status ?? (ep.response === null ? 204 : 200)}`);
    if (ep.errors?.length) lines.push(`errors: ${JSON.stringify(ep.errors)}`);
    if (ep.idempotent) lines.push('idempotent: true');
    if (ep.audited) lines.push('audited: true');
    if (ep.approval) lines.push(`approval: ${str(ep.approval)}`);
    if (ep.events?.length) lines.push(`events: ${JSON.stringify(ep.events)}`);
    if (ep.screens?.length) lines.push(`screens: ${JSON.stringify(ep.screens)}`);
    lines.push(`phase: ${ep.phase ?? mod.phase}`);
    body.push(`  ${ep.id}: {\n${lines.map((l) => `    ${l},`).join('\n')}\n  },`);
  }
  body.push('});\n');

  /* ---------------- manifest */
  body.push('/* ------------------------------------------------------------------ module spec */\n');
  const sm = Object.fromEntries((mod.stateMachines ?? []).map((m) => [m.name, { field: m.field, initial: m.initial ?? m.transitions[0]?.[0] ?? null, transitions: m.transitions }]));
  const consumes = Object.fromEntries(mergeConsumes(mod).map((c) => [c.name, c.does]));
  const jobs = Object.fromEntries((mod.jobs ?? []).map((j) => [j.name, { schedule: j.schedule, does: j.does }]));
  const settings = Object.fromEntries((mod.settings ?? []).map((s) => [s.key, { default: s.default, desc: s.desc }]));
  const tables = Object.fromEntries(plans.map(({ table, columns }) => [table.name, Object.fromEntries(columns.map((c) => [c.name, { type: c.sqlType, nullable: c.nullable || c.sqlType === 'tsvector' }]))]));
  body.push(`export const spec = defineModuleSpec({
  name: ${str(mod.name)},
  title: ${str(mod.title)},
  group: ${str(mod.group)},
  phase: ${mod.phase},
  chapters: ${JSON.stringify(mod.chapters ?? [])},
  summary: ${str(mod.summary)},
  dependsOn: ${JSON.stringify(mod.dependsOn ?? [])},
  optionalDeps: ${JSON.stringify(mod.optionalDeps ?? [])},
  publicApi: ${JSON.stringify((mod.publicApi ?? []).map((f) => f.name))},
  permissions: ${JSON.stringify(mod.permissions ?? [], null, 2).replace(/\n/g, '\n  ')},
  approvalActions: ${JSON.stringify(mod.approvalActions ?? [], null, 2).replace(/\n/g, '\n  ')},
  stateMachines: ${JSON.stringify(sm, null, 2).replace(/\n/g, '\n  ')},
  events: {
    publishes: {${publishes.map((e) => `\n      ${str(e.name)}: { when: ${str(e.when)}, payload: () => ${eventTypeName(e.name)} },`).join('')}
    },
    consumes: ${JSON.stringify(consumes, null, 2).replace(/\n/g, '\n    ')},
  },
  jobs: ${JSON.stringify(jobs, null, 2).replace(/\n/g, '\n  ')},
  settings: ${JSON.stringify(settings, null, 2).replace(/\n/g, '\n  ')},
  errorCodes: ${JSON.stringify(mod.errorCodes ?? {}, null, 2).replace(/\n/g, '\n  ')},
  tables: ${JSON.stringify(tables, null, 2).replace(/\n/g, '\n  ')},
  endpoints,
});
`);

  /* ---------------- type registration */
  body.push(`declare module '../kernel/events/event-map.js' {
  interface EventMap {${publishes.map((e) => `\n    ${str(e.name)}: ${eventTypeName(e.name)};`).join('')}
  }
}

declare module '../kernel/module-system/public-apis.js' {
  interface PublicApiMap {
    ${str(mod.name)}: ${P}PublicApi;
  }
  interface ModuleDbMap {
    ${str(mod.name)}: ${P}Db;
  }
}
`);

  const imports = [...ctx.imports].filter((m) => m !== 'common' && m !== mod.name).sort();
  const header = [
    GENERATED(`docs/api/spec/modules/${mod.name}.json`),
    `/* eslint-disable */`,
    `import { z } from 'zod';`,
    `import type { Generated, Json } from '../kernel/db/types.js';`,
    `import { defineEndpoints, defineModuleSpec } from '../kernel/spec/define.js';`,
    `import * as common from './common.js';`,
    ...imports.map((m) => `import * as ${camel(m)} from './${m}.js';`),
    '',
    `/** ${mod.title}: ${mod.summary.replace(/\*\//g, '')} */`,
    '',
  ];
  return { code: `${header.join('\n')}\n${body.join('\n')}`, problems: ctx.problems, warnings: ctx.warnings };
}

function fieldsOf(ctx: TypeContext, obj: Record<string, unknown>, where: string) {
  return fieldsOfParsed(ctx.objectParsed(obj as never, where));
}

function fieldsOfParsed(p: Parsed): [string, Parsed][] {
  return p.node.k === 'object' ? p.node.fields : [];
}

function schemaOf(ctx: TypeContext, expr: unknown, where: string): string {
  const p = ctx.parse(expr as never, where);
  const r = ctx.zod(p, 'data', '    ');
  return p.optional ? `${r.code}.nullish()` : r.code;
}
